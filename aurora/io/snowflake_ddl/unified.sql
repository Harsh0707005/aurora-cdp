-- Aurora CDP :: Unified tables (Snowflake)
-- Unified_Preprocessed_Raw: one row per source record after standardisation and blocklist stripping.
CREATE TABLE IF NOT EXISTS UNIFIED_PREPROCESSED_RAW (
  DATASOURCE      VARCHAR      NOT NULL COMMENT 'source system name',
  PK              VARCHAR      NOT NULL COMMENT 'source primary key',
  RID             NUMBER(19,0)          COMMENT 'run-local integer row id',
  GIVEN_NAME      VARCHAR, SURNAME VARCHAR, FULL_NAME VARCHAR,
  EMAIL           VARCHAR, PHONE VARCHAR, ADDRESS VARCHAR, CITY VARCHAR, STATE VARCHAR,
  POSTAL          VARCHAR, COUNTRY VARCHAR, BIRTHDATE VARCHAR, LOYALTY_ID VARCHAR, GENDER VARCHAR,
  UPDATED_AT      VARCHAR               COMMENT 'source-side last update (ISO date)',
  TRUTH_ID        VARCHAR               COMMENT 'synthetic ground truth only; NULL in production',
  EMAIL_STD VARCHAR, EMAIL_CANON VARCHAR, PHONE_STD VARCHAR, GIVEN_STD VARCHAR, SURNAME_STD VARCHAR,
  GIVEN_NICK VARCHAR, STREET_STD VARCHAR, HOUSE_NO VARCHAR, POSTAL_STD VARCHAR, DOB_STD VARCHAR,
  HAS_BLV         BOOLEAN               COMMENT 'a blocklisted value was stripped from this row',
  JOB_ID          VARCHAR      NOT NULL,
  PRIMARY KEY (DATASOURCE, PK)
) COMMENT = 'Standardised input rows for one identity run';

-- Unified_Coalesced: preprocessed rows + cluster membership and hygiene flags.
CREATE TABLE IF NOT EXISTS UNIFIED_COALESCED (
  DATASOURCE VARCHAR NOT NULL, PK VARCHAR NOT NULL, RID NUMBER(19,0),
  AURORA_ID       VARCHAR      NOT NULL COMMENT 'stable customer id (UUIDv5)',
  CLUSTER_ID      NUMBER(19,0) NOT NULL COMMENT 'run-local cluster id after hygiene',
  COMPONENT_ID    NUMBER(19,0)          COMMENT 'connected-component id before hygiene carving',
  IS_SUPERSIZED   BOOLEAN, SUPERSIZED_ID NUMBER(19,0) COMMENT 'original over-sized component id',
  REP_DS VARCHAR, REP_PK VARCHAR COMMENT 'representative (seed) record of the cluster',
  HAS_BLV BOOLEAN,
  GIVEN_NAME VARCHAR, SURNAME VARCHAR, FULL_NAME VARCHAR, EMAIL VARCHAR, PHONE VARCHAR, ADDRESS VARCHAR,
  CITY VARCHAR, STATE VARCHAR, POSTAL VARCHAR, COUNTRY VARCHAR, BIRTHDATE VARCHAR, LOYALTY_ID VARCHAR,
  GENDER VARCHAR, UPDATED_AT VARCHAR, TRUTH_ID VARCHAR,
  EMAIL_STD VARCHAR, EMAIL_CANON VARCHAR, PHONE_STD VARCHAR, GIVEN_STD VARCHAR, SURNAME_STD VARCHAR,
  GIVEN_NICK VARCHAR, STREET_STD VARCHAR, HOUSE_NO VARCHAR, POSTAL_STD VARCHAR, DOB_STD VARCHAR,
  JOB_ID VARCHAR NOT NULL,
  PRIMARY KEY (DATASOURCE, PK)
) COMMENT = 'Every source row with its resolved cluster';

-- Unified_Customer: the slim serving projection (one row per source row).
CREATE TABLE IF NOT EXISTS UNIFIED_CUSTOMER (
  DATASOURCE VARCHAR NOT NULL, PK VARCHAR NOT NULL,
  AURORA_ID VARCHAR NOT NULL, CLUSTER_ID NUMBER(19,0) NOT NULL, TRUTH_ID VARCHAR, JOB_ID VARCHAR NOT NULL,
  GIVEN_NAME VARCHAR, SURNAME VARCHAR, FULL_NAME VARCHAR, EMAIL VARCHAR, PHONE VARCHAR, ADDRESS VARCHAR,
  CITY VARCHAR, STATE VARCHAR, POSTAL VARCHAR, COUNTRY VARCHAR, BIRTHDATE VARCHAR, LOYALTY_ID VARCHAR,
  GENDER VARCHAR, UPDATED_AT VARCHAR,
  EMAIL_STD VARCHAR, EMAIL_CANON VARCHAR, PHONE_STD VARCHAR, GIVEN_STD VARCHAR, SURNAME_STD VARCHAR,
  GIVEN_NICK VARCHAR, STREET_STD VARCHAR, HOUSE_NO VARCHAR, POSTAL_STD VARCHAR, DOB_STD VARCHAR,
  IS_SUPERSIZED BOOLEAN, HAS_BLV BOOLEAN,
  PRIMARY KEY (DATASOURCE, PK)
) CLUSTER BY (AURORA_ID) COMMENT = 'Source rows keyed by stable aurora_id';

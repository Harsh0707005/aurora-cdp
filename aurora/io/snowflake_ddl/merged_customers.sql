-- Aurora CDP :: Merged_Customers (Snowflake) — one golden row per aurora_id.
-- Survivorship: most-complete source row wins, ties -> most recent UPDATED_AT, then per-field first non-null.
CREATE TABLE IF NOT EXISTS MERGED_CUSTOMERS (
  AURORA_ID VARCHAR NOT NULL PRIMARY KEY,
  REP_DS VARCHAR, REP_PK VARCHAR COMMENT 'row that won survivorship',
  GIVEN_NAME VARCHAR, SURNAME VARCHAR, FULL_NAME VARCHAR, EMAIL VARCHAR, PHONE VARCHAR, ADDRESS VARCHAR,
  CITY VARCHAR, STATE VARCHAR, POSTAL VARCHAR, COUNTRY VARCHAR, BIRTHDATE VARCHAR, LOYALTY_ID VARCHAR,
  GENDER VARCHAR, UPDATED_AT VARCHAR,
  EMAIL_STD VARCHAR, EMAIL_CANON VARCHAR, PHONE_STD VARCHAR, GIVEN_STD VARCHAR, SURNAME_STD VARCHAR,
  GIVEN_NICK VARCHAR, STREET_STD VARCHAR, HOUSE_NO VARCHAR, POSTAL_STD VARCHAR, DOB_STD VARCHAR,
  RECORD_COUNT NUMBER(10,0), SOURCES ARRAY
) COMMENT = 'Golden record per customer';

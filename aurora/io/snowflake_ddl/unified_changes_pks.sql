-- Aurora CDP :: Unified_Changes_PKs (Snowflake) — record-level CDC, append-only across runs.
CREATE TABLE IF NOT EXISTS UNIFIED_CHANGES_PKS (
  DATASOURCE  VARCHAR NOT NULL, PK VARCHAR NOT NULL,
  CURRENT_ID  VARCHAR, PREVIOUS_ID VARCHAR,
  CHANGE_TYPE VARCHAR NOT NULL COMMENT 'added|removed|moved',
  JOB_ID      VARCHAR NOT NULL, TS TIMESTAMP_TZ NOT NULL,
  LINEAGE     VARCHAR
) CLUSTER BY (JOB_ID, DATASOURCE) COMMENT = 'Records whose aurora_id changed in a run';

-- Supporting tables
CREATE TABLE IF NOT EXISTS STABLE_ID_MAPPING (
  CLUSTER_ID NUMBER(19,0), AURORA_ID VARCHAR NOT NULL, PREVIOUS_ID VARCHAR, CHANGE_TYPE VARCHAR,
  JOB_ID VARCHAR NOT NULL
) COMMENT = 'Per-run cluster -> aurora_id assignment with inheritance';

CREATE TABLE IF NOT EXISTS LINEAGE (
  AURORA_ID VARCHAR NOT NULL, DATASOURCE VARCHAR NOT NULL, PK VARCHAR NOT NULL,
  CLUSTER_ID NUMBER(19,0), SUPERSIZED_ID NUMBER(19,0), JOB_ID VARCHAR NOT NULL, LINEAGE VARCHAR
) CLUSTER BY (AURORA_ID) COMMENT = 'Which run placed which record under which id';
